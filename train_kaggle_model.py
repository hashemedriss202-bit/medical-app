# قائمة جميع الأعراض
all_symptoms = set()
for symptoms in diseases_database.values():
    all_symptoms.update(symptoms)
symptom_list = sorted(list(all_symptoms))

print(f"📊 عدد الأمراض: {len(diseases_database)}")
print(f"📊 عدد الأعراض الفريدة: {len(symptom_list)}")

# توليد بيانات التدريب
training_data = []
for disease, symptoms in diseases_database.items():
    for _ in range(100):
        num_symptoms = np.random.randint(3, min(7, len(symptoms)) + 1)
        selected = list(np.random.choice(symptoms, num_symptoms, replace=False))
        training_data.append({"symptoms": selected, "disease": disease})

# تحويل البيانات إلى مصفوفات
symptom_to_idx = {s: i for i, s in enumerate(symptom_list)}
X = []
y = []
for item in training_data:
    row = [0] * len(symptom_list)
    for s in item["symptoms"]:
        if s in symptom_to_idx:
            row[symptom_to_idx[s]] = 1
    X.append(row)
    y.append(item["disease"])

# ترميز الأمراض
label_encoder = LabelEncoder()
y_encoded = label_encoder.fit_transform(y)

# تدريب النموذج
print("🔄 جاري تدريب نموذج Random Forest...")
model = RandomForestClassifier(n_estimators=200, max_depth=25, random_state=42)
model.fit(X, y_encoded)

# تقييم النموذج
X_train, X_test, y_train, y_test = train_test_split(X, y_encoded, test_size=0.2, random_state=42)
model.fit(X_train, y_train)
y_pred = model.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)
print(f"🎯 دقة النموذج: {accuracy * 100:.2f}%")

